local function ScheduleAfter(sec, fn)
  local scheduled = false
  pcall(function()
    local tk = require("common.time_ticker")
    if tk and tk.AddTimerOnce then
      tk.AddTimerOnce(sec, fn)
      scheduled = true
    end
  end)
  if not scheduled then
    pcall(function()
      local tm = require("timer")
      if tm and tm.SetGameTimer then
        tm.SetGameTimer(sec, false, fn)
        scheduled = true
      end
    end)
  end
  if not scheduled then
    pcall(function()
      local pc = ESP.GetController()
      if pc and pc.AddGameTimer then
        pc:AddGameTimer(sec, false, fn)
        scheduled = true
      end
    end)
  end
  return scheduled
end

